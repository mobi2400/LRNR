import type { JSX } from 'react';

import { AppShell } from '@/components/app-shell/AppShell';
import { CompleteLessonButton } from '@/components/lesson/CompleteLessonButton';
import { assertUnlockedOwnerSession, getSessionAccessState } from '@/server/session';
import { getCurrentLesson } from '@/services/lesson.service';

export default async function CurrentLessonPage(): Promise<JSX.Element> {
  const state = await getSessionAccessState();

  assertUnlockedOwnerSession(state);

  const currentLesson = await getCurrentLesson({
    userId: state.userId,
  });
  const lesson = currentLesson.lesson;

  return (
    <AppShell
      activeRoute="lesson-current"
      identity={state.email ?? state.userId}
      unlockExpiresAt={state.unlockedUntil}
    >
      <section className="cockpit-page">
        <header className="cockpit-hero cockpit-hero--compact">
          <div>
            <p className="cockpit-kicker">Daily Lesson</p>
            <h2>{lesson?.title ?? 'No persisted lesson is ready yet.'}</h2>
            <p>
              {lesson?.objective ??
                `Current state: ${currentLesson.reasonIfEmpty ?? 'not_ready'}.`}
            </p>
          </div>
        </header>
        {lesson === null ? (
          <article className="cockpit-panel cockpit-panel--primary">
            <p className="cockpit-panel__label">Lesson status</p>
            <p>
              Teaching content is generated by the backend workflow and then
              read here. This page does not generate a lesson during normal load.
            </p>
          </article>
        ) : (
          <div className="cockpit-grid cockpit-grid--lesson">
            <article className="cockpit-panel cockpit-panel--primary">
              <p className="cockpit-panel__label">Mental model</p>
              <h3>{lesson.mentalModel}</h3>
              <p>{lesson.nextAction}</p>
            </article>
            <article className="cockpit-panel">
              <p className="cockpit-panel__label">Explanation</p>
              {lesson.explanation.map((section) => (
                <section className="lesson-section" key={section.heading}>
                  <h3>{section.heading}</h3>
                  <p>{section.body}</p>
                </section>
              ))}
            </article>
            <article className="cockpit-panel">
              <p className="cockpit-panel__label">Diagram</p>
              <pre className="lesson-code">{lesson.diagram.content}</pre>
            </article>
            <article className="cockpit-panel">
              <p className="cockpit-panel__label">Code example</p>
              {lesson.codeExamples.map((example) => (
                <section className="lesson-section" key={example.title}>
                  <h3>{example.title}</h3>
                  <pre className="lesson-code">{example.code}</pre>
                  <p>{example.explanation}</p>
                </section>
              ))}
            </article>
            <article className="cockpit-panel">
              <p className="cockpit-panel__label">Common mistakes</p>
              <ul className="cockpit-list">
                {lesson.commonMistakes.map((mistake) => (
                  <li key={mistake}>{mistake}</li>
                ))}
              </ul>
            </article>
            <article className="cockpit-panel">
              <p className="cockpit-panel__label">Next action</p>
              <div className="cockpit-chip-row">
                <a className="workspace-button workspace-button--secondary" href="/lesson/review">
                  Move to review
                </a>
                <a className="workspace-button workspace-button--secondary" href="/curriculum">
                  Open curriculum map
                </a>
              </div>
              <CompleteLessonButton sessionId={lesson.sessionId} />
            </article>
          </div>
        )}
      </section>
    </AppShell>
  );
}
